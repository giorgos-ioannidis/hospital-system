-- Επαύξηση 3: Ιατρικός Φάκελος & Λοιπά (UC-12, UC-17–UC-21, UC-23, UC-25, UC-26, UC-28).

-- UC-17/18 Κλίνες. Το φύλο του θαλάμου προκύπτει από τους νοσηλευόμενους (άδειος θάλαμος δέχεται όλους).
CREATE TABLE ward (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT       NOT NULL REFERENCES department (id),
    name          VARCHAR(100) NOT NULL,
    near_station  BOOLEAN      NOT NULL DEFAULT FALSE,
    UNIQUE (department_id, name)
);

CREATE TABLE bed (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_id   BIGINT      NOT NULL REFERENCES ward (id),
    label     VARCHAR(20) NOT NULL,
    isolation BOOLEAN     NOT NULL DEFAULT FALSE,
    UNIQUE (ward_id, label)
);

CREATE TABLE admission (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id    BIGINT    NOT NULL REFERENCES app_user (id),
    bed_id        BIGINT    NOT NULL REFERENCES bed (id),
    severity      INT       NOT NULL CHECK (severity BETWEEN 1 AND 3),
    isolation     BOOLEAN   NOT NULL DEFAULT FALSE,
    admitted_at   TIMESTAMP NOT NULL,
    discharged_at TIMESTAMP,
    admitted_by   BIGINT REFERENCES app_user (id)
);

-- UC-19 Ιατρικό ιστορικό. Οι εγγραφές δεν διορθώνονται ούτε διαγράφονται.
CREATE TABLE medical_record (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT    NOT NULL UNIQUE REFERENCES app_user (id),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE record_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id  BIGINT        NOT NULL REFERENCES medical_record (id),
    author_id  BIGINT        NOT NULL REFERENCES app_user (id),
    entry_type VARCHAR(20)   NOT NULL CHECK (entry_type IN ('DIAGNOSIS', 'MEDICATION', 'ALLERGY', 'NOTE', 'PATIENT_NOTE')),
    text       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP     NOT NULL
);

-- NFR-02: κάθε πρόσβαση και απόπειρα πρόσβασης σε φάκελο.
CREATE TABLE access_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id),
    patient_id  BIGINT      NOT NULL REFERENCES app_user (id),
    action      VARCHAR(20) NOT NULL,
    allowed     BOOLEAN     NOT NULL,
    occurred_at TIMESTAMP   NOT NULL
);

-- UC-20/21 Εξετάσεις: παραγγελία και αποτέλεσμα στην ίδια γραμμή.
CREATE TABLE exam_order (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT        NOT NULL REFERENCES app_user (id),
    doctor_id   BIGINT        NOT NULL REFERENCES app_user (id),
    service_id  BIGINT        NOT NULL REFERENCES medical_service (id),
    notes       VARCHAR(500),
    status      VARCHAR(20)   NOT NULL CHECK (status IN ('ORDERED', 'COMPLETED', 'CANCELLED')),
    ordered_at  TIMESTAMP     NOT NULL,
    result_text VARCHAR(4000),
    result_at   TIMESTAMP
);

-- UC-23 Υπερωρίες ανά μήνα: υπολογίζονται από το ενεργό πρόγραμμα και εγκρίνονται από τον Προϊστάμενο.
CREATE TABLE overtime (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id     BIGINT      NOT NULL REFERENCES app_user (id),
    period_start DATE        NOT NULL,
    hours        INT         NOT NULL CHECK (hours >= 0),
    status       VARCHAR(20) NOT NULL CHECK (status IN ('APPROVED', 'REJECTED')),
    decided_by   BIGINT      NOT NULL REFERENCES app_user (id),
    decided_at   TIMESTAMP   NOT NULL,
    UNIQUE (staff_id, period_start)
);

-- UC-28 Αξιολόγηση επίσκεψης.
CREATE TABLE rating (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT       NOT NULL UNIQUE REFERENCES appointment (id),
    stars          INT          NOT NULL CHECK (stars BETWEEN 1 AND 5),
    comment        VARCHAR(500),
    created_at     TIMESTAMP    NOT NULL
);

CREATE INDEX idx_admission_bed ON admission (bed_id, discharged_at);
CREATE INDEX idx_admission_patient ON admission (patient_id);
CREATE INDEX idx_access_log_patient ON access_log (patient_id, occurred_at);
CREATE INDEX idx_exam_order_patient ON exam_order (patient_id, ordered_at);

