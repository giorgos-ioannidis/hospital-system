-- Σχήμα Επαυξήσεων 1 και 2 (UC-01 έως UC-16, UC-27).
-- Κοινό σχήμα για H2 (MODE=PostgreSQL) και PostgreSQL.

CREATE TABLE hospital (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(200) NOT NULL,
    address VARCHAR(300)
);

CREATE TABLE department (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT       NOT NULL REFERENCES hospital (id),
    name        VARCHAR(150) NOT NULL,
    floor       INT,
    UNIQUE (hospital_id, name)
);

CREATE TABLE specialty (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE
);

-- Single-table inheritance: User → Supervisor, Patient, HealthStaff → Doctor, Nurse (στήλη role).
CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role            VARCHAR(20)  NOT NULL CHECK (role IN ('SUPERVISOR', 'DOCTOR', 'NURSE', 'PATIENT')),
    username        VARCHAR(50)  NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    first_name      VARCHAR(100) NOT NULL,
    last_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(200) NOT NULL UNIQUE,
    phone           VARCHAR(30),
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_attempts INT          NOT NULL DEFAULT 0,
    locked          BOOLEAN      NOT NULL DEFAULT FALSE,
    -- HealthStaff / Supervisor
    department_id   BIGINT REFERENCES department (id),
    specialty_id    BIGINT REFERENCES specialty (id),
    -- Patient
    amka            VARCHAR(11) UNIQUE CHECK (amka IS NULL OR LENGTH(amka) = 11),
    gender          VARCHAR(1) CHECK (gender IS NULL OR gender IN ('M', 'F')),
    birth_date      DATE
);

-- Ελάχιστη στελέχωση ανά τμήμα, τύπο βάρδιας και ειδικότητα (παράμετροι UC-03).
CREATE TABLE staffing_requirement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT      NOT NULL REFERENCES department (id),
    specialty_id  BIGINT      NOT NULL REFERENCES specialty (id),
    shift_type    VARCHAR(20) NOT NULL CHECK (shift_type IN ('MORNING', 'AFTERNOON', 'NIGHT', 'ON_CALL')),
    min_staff     INT         NOT NULL CHECK (min_staff >= 0),
    UNIQUE (department_id, specialty_id, shift_type)
);

CREATE TABLE schedule (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT      NOT NULL REFERENCES department (id),
    period_start  DATE        NOT NULL,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_by      BIGINT REFERENCES app_user (id),
    max_weekly_hours INT         NOT NULL CHECK (max_weekly_hours > 0)
);

CREATE TABLE shift (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id  BIGINT      NOT NULL REFERENCES schedule (id) ON DELETE CASCADE,
    specialty_id BIGINT      NOT NULL REFERENCES specialty (id),
    shift_date   DATE        NOT NULL,
    shift_type   VARCHAR(20) NOT NULL CHECK (shift_type IN ('MORNING', 'AFTERNOON', 'NIGHT', 'ON_CALL')),
    min_staff    INT         NOT NULL,
    UNIQUE (schedule_id, specialty_id, shift_date, shift_type)
);

CREATE TABLE assignment (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL REFERENCES shift (id) ON DELETE CASCADE,
    staff_id BIGINT NOT NULL REFERENCES app_user (id),
    UNIQUE (shift_id, staff_id)
);

CREATE TABLE leave_request (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id    BIGINT      NOT NULL REFERENCES app_user (id),
    leave_type  VARCHAR(20) NOT NULL CHECK (leave_type IN ('ANNUAL', 'SICK', 'TRAINING', 'OTHER')),
    start_date  DATE        NOT NULL,
    end_date    DATE        NOT NULL,
    status      VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reason      VARCHAR(500),
    decided_by  BIGINT REFERENCES app_user (id),
    decided_at  TIMESTAMP,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

CREATE TABLE absence (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id    BIGINT    NOT NULL REFERENCES app_user (id),
    start_date  DATE      NOT NULL,
    end_date    DATE      NOT NULL,
    reason      VARCHAR(500),
    declared_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

-- Επαύξηση 2: Ραντεβού & Πόροι
CREATE TABLE room (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT       NOT NULL REFERENCES department (id),
    name          VARCHAR(100) NOT NULL,
    UNIQUE (department_id, name)
);

CREATE TABLE equipment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT       NOT NULL REFERENCES department (id),
    name          VARCHAR(100) NOT NULL
);

-- Υπηρεσία/είδος ραντεβού (π.χ. Τακτική επίσκεψη, Υπέρηχος καρδιάς). Αν θέλει εξοπλισμό, δεσμεύεται κι αυτός.
CREATE TABLE medical_service (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT        NOT NULL REFERENCES department (id),
    name          VARCHAR(150)  NOT NULL,
    price         NUMERIC(8, 2) NOT NULL CHECK (price >= 0),
    equipment_id  BIGINT REFERENCES equipment (id)
);

CREATE TABLE office_hours (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id    BIGINT NOT NULL REFERENCES app_user (id),
    room_id      BIGINT NOT NULL REFERENCES room (id),
    work_date    DATE   NOT NULL,
    start_time   TIME   NOT NULL,
    end_time     TIME   NOT NULL,
    slot_minutes INT    NOT NULL CHECK (slot_minutes BETWEEN 5 AND 240),
    CHECK (end_time > start_time)
);

CREATE TABLE appointment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(12)  NOT NULL UNIQUE,
    patient_id   BIGINT       NOT NULL REFERENCES app_user (id),
    doctor_id    BIGINT       NOT NULL REFERENCES app_user (id),
    room_id      BIGINT       NOT NULL REFERENCES room (id),
    equipment_id BIGINT REFERENCES equipment (id),
    service_id   BIGINT       NOT NULL REFERENCES medical_service (id),
    start_at     TIMESTAMP    NOT NULL,
    end_at       TIMESTAMP    NOT NULL,
    reason       VARCHAR(500),
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('BOOKED', 'CONFIRMED', 'COMPLETED', 'NO_SHOW', 'CANCELLED')),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_at > start_at)
);

CREATE TABLE payment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT        NOT NULL UNIQUE REFERENCES appointment (id),
    method          VARCHAR(20)   NOT NULL CHECK (method IN ('CARD', 'AT_DESK')),
    amount          NUMERIC(8, 2) NOT NULL,
    status          VARCHAR(20)   NOT NULL CHECK (status IN ('PENDING', 'PAID')),
    transaction_ref VARCHAR(64),
    paid_at         TIMESTAMP
);

-- UC-27: ουρά ειδοποιήσεων. Αποστολή από το DailyReminderJob, επανάληψη ανά 30' έως 3 φορές (FR-31).
CREATE TABLE notification (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id    BIGINT        NOT NULL REFERENCES app_user (id),
    channel         VARCHAR(10)   NOT NULL CHECK (channel IN ('EMAIL', 'SMS')),
    subject         VARCHAR(200)  NOT NULL,
    message         VARCHAR(1000) NOT NULL,
    status          VARCHAR(10)   NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    attempts        INT           NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP     NOT NULL,
    sent_at         TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_user_department ON app_user (department_id);
CREATE INDEX idx_shift_date ON shift (shift_date);
CREATE INDEX idx_assignment_staff ON assignment (staff_id);
CREATE INDEX idx_leave_staff_dates ON leave_request (staff_id, start_date, end_date);
CREATE INDEX idx_absence_staff_dates ON absence (staff_id, start_date, end_date);
CREATE INDEX idx_office_hours_doctor_date ON office_hours (doctor_id, work_date);
CREATE INDEX idx_office_hours_room_date ON office_hours (room_id, work_date);
CREATE INDEX idx_appointment_doctor_start ON appointment (doctor_id, start_at);
CREATE INDEX idx_appointment_room_start ON appointment (room_id, start_at);
CREATE INDEX idx_appointment_patient ON appointment (patient_id);
CREATE INDEX idx_notification_due ON notification (status, next_attempt_at);
